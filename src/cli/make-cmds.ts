/* CLI handlers for make, run <stage>, qa and qa:checks. */
import path from "node:path";
import { exists, readJson } from "../core/fsutil";
import { log } from "../core/log";
import { BookConfig } from "../schemas/book";
import { CourseMap } from "../schemas/course";
import { QA_CHECKS } from "../qa/registry";
import { bookConfigFile, courseMapFile } from "../pipeline/artifacts";
import { runMake, runSingleStage } from "../pipeline/runner";
import { AwaitingResearchError, STAGE_IDS, type MakeOptions, type StageId } from "../pipeline/types";

export interface MakeCliOptions {
  book?: string;
  chapter?: string;
  part?: string;
  all?: boolean;
  lang?: string;
  llm?: string;
  model?: string;
  tts?: string;
  handoff?: string;
  draft?: boolean;
  scenes?: string;
  until?: string;
  force?: string | boolean;
  resume?: boolean;
  record?: boolean;
  nonInteractive?: boolean;
  review?: boolean;
  json?: boolean;
}

function list(s: string | undefined): string[] | undefined {
  if (!s) return undefined;
  const v = s
    .split(",")
    .map((x) => x.trim())
    .filter(Boolean);
  return v.length ? v : undefined;
}

function stageId(s: string, flag: string): StageId {
  const id = s.trim().toUpperCase() as StageId;
  if (!STAGE_IDS.includes(id)) throw new Error(`${flag}: unknown stage ${s} (use one of ${STAGE_IDS.join(", ")})`);
  return id;
}

export function toMakeOptions(o: MakeCliOptions, chapterId: string, partId: string): MakeOptions {
  if (!o.book) throw new Error("--book <id> is required");
  const scenes = list(o.scenes)?.map((x) => {
    const n = Number(x);
    if (!Number.isInteger(n) || n < 0) throw new Error(`--scenes: "${x}" is not a scene index`);
    return n;
  });
  const handoff = o.handoff as MakeOptions["handoff"];
  if (handoff && handoff !== "exit" && handoff !== "poll") throw new Error("--handoff must be exit or poll");
  return {
    bookId: o.book,
    chapterId,
    partId,
    langs: list(o.lang),
    llm: o.llm,
    model: o.model,
    tts: o.tts,
    handoff: handoff ?? (o.nonInteractive || !process.stdout.isTTY ? "exit" : undefined),
    draft: Boolean(o.draft),
    scenes,
    until: o.until ? stageId(o.until, "--until") : undefined,
    force: o.force === true ? true : typeof o.force === "string" ? list(o.force)?.map((x) => stageId(x, "--force")) : undefined,
    resume: Boolean(o.resume),
    record: Boolean(o.record),
    nonInteractive: Boolean(o.nonInteractive),
    noReview: o.review === false,
  };
}

function printAwaitingResearch(e: AwaitingResearchError): void {
  process.stderr.write(`[WAIT] ${e.reason}\n`);
  process.stderr.write(`       1. Paste the prompt in ${e.pasteFile} into NotebookLM (with your book uploaded).\n`);
  process.stderr.write(`       2. Paste the full answer into ${e.dropFile}.\n`);
  process.stderr.write("       3. Re-run the same command (add --resume); finished stages are cached.\n");
  process.stdout.write(`AWAITING_RESEARCH ${e.dropFile}\n`);
}

/** Every part the book's deliverables select, in order: chapters, then orientation, then synthesis. */
export function deliverableParts(cfg: BookConfig, map: CourseMap): { chapterId: string; partId: string }[] {
  const range = cfg.deliverables.chapters;
  const inRange = (n: number) => range === "all" || (n >= range.from && n <= range.to);
  const out: { chapterId: string; partId: string }[] = [];
  for (const c of map.chapters) if (c.kind === "chapter_part" && inRange(c.number)) for (const pt of c.parts) out.push({ chapterId: c.id, partId: pt.id });
  for (const kind of ["orientation", "synthesis"] as const) {
    if (!cfg.deliverables[kind]) continue;
    for (const c of map.chapters) if (c.kind === kind) for (const pt of c.parts) out.push({ chapterId: c.id, partId: pt.id });
  }
  return out;
}

/** Chapter id for chapter number n, as generated by the wizard (1 -> ch + "01"). */
export function chapterIdFor(n: number): string {
  return `ch${String(n).padStart(2, "0")}`;
}

export async function runMakeCmd(o: MakeCliOptions): Promise<number> {
  try {
    if (!o.all) {
      if (!o.chapter) throw new Error("--chapter <id> is required (or use --all)");
      const r = await runMake(toMakeOptions(o, o.chapter, o.part ?? "p1"));
      return r.code;
    }
    const book = o.book;
    if (!book) throw new Error("--book <id> is required");
    let cfgFile = bookConfigFile(book);
    if (!exists(cfgFile) || !exists(courseMapFile(book))) {
      const first = exists(cfgFile) ? BookConfig.parse(readJson(cfgFile)).chapters[0].id : undefined;
      const boot = await runMake({ ...toMakeOptions(o, o.chapter ?? first ?? chapterIdFor(1), "p1"), until: "S2", force: undefined });
      if (boot.code !== 0) return boot.code;
      cfgFile = bookConfigFile(book);
    }
    const cfg = BookConfig.parse(readJson(cfgFile));
    const map = CourseMap.parse(readJson(courseMapFile(book)));
    const parts = deliverableParts(cfg, map);
    log.info(`make --all: ${parts.length} parts (${parts.map((x) => `${x.chapterId}/${x.partId}`).join(", ")})`);
    let worst = 0;
    for (const x of parts) {
      const r = await runMake(toMakeOptions(o, x.chapterId, x.partId));
      if (r.code !== 0) worst = r.code;
    }
    return worst;
  } catch (e) {
    if (e instanceof AwaitingResearchError) {
      printAwaitingResearch(e);
      return e.exitCode;
    }
    throw e;
  }
}

export async function runStageCmd(stage: string, o: MakeCliOptions): Promise<number> {
  if (!o.chapter) throw new Error("--chapter <id> is required");
  try {
    await runSingleStage(toMakeOptions(o, o.chapter, o.part ?? "p1"), stageId(stage, "run"));
    return 0;
  } catch (e) {
    if (e instanceof AwaitingResearchError) {
      printAwaitingResearch(e);
      return e.exitCode;
    }
    throw e;
  }
}

export async function runQaCmd(o: MakeCliOptions & { fixture?: string; out?: string }): Promise<number> {
  if (o.fixture) {
    const { runFixtureQa } = await import("../qa/fixture");
    return runFixtureQa({
      fixture: path.resolve(o.fixture),
      out: path.resolve(o.out ?? path.join("out", "qa-fixture")),
      draft: Boolean(o.draft),
      json: Boolean(o.json),
      langs: list(o.lang),
    });
  }
  if (!o.chapter) throw new Error("--chapter <id> is required (or --fixture <dir>)");
  const opts = toMakeOptions(o, o.chapter, o.part ?? "p1");
  const report = await runSingleStage(opts, "S12");
  if (!report) throw new Error("QA did not write a report");
  if (o.json) process.stdout.write(JSON.stringify(report, null, 2) + "\n");
  const blocking = report.findings.filter((f) => f.severity === "BLOCKER" || f.severity === "HIGH");
  for (const f of blocking) log.fail(`${f.id} ${f.severity}${f.lang ? ` [${f.lang}]` : ""}: ${f.message}`);
  if (report.release.releasable) log.ok("QA: releasable (0 BLOCKER, 0 HIGH)");
  else log.warn(`QA: not releasable (${blocking.length} BLOCKER/HIGH findings)`);
  return report.release.releasable ? 0 : 2;
}

export function runQaChecksCmd(json: boolean): number {
  if (json) {
    process.stdout.write(JSON.stringify({ checks: QA_CHECKS }, null, 2) + "\n");
    return 0;
  }
  for (const c of QA_CHECKS) process.stdout.write(`${c.id.padEnd(6)} ${c.layer.padEnd(3)} ${c.title}\n`);
  process.stdout.write(`${QA_CHECKS.length} checks\n`);
  return 0;
}

export async function runPreflightCmd(
  o: MakeCliOptions & { compiled?: boolean; stills?: boolean; release?: boolean },
): Promise<number> {
  if (!o.book) throw new Error("--book <id> is required");
  if (!o.chapter) throw new Error("--chapter <id> is required");
  const { runPreflight } = await import("../qa/preflight");
  const res = await runPreflight({
    bookId: o.book,
    chapterId: o.chapter,
    partId: o.part ?? "p1",
    langs: list(o.lang),
    compiled: Boolean(o.compiled),
    stills: Boolean(o.stills),
    release: Boolean(o.release),
  });
  if (o.json) {
    process.stdout.write(JSON.stringify(res, null, 2) + "\n");
    return res.ok ? 0 : 1;
  }
  const blocking = res.findings.filter((f) => f.severity === "BLOCKER" || f.severity === "HIGH");
  for (const f of blocking) {
    const loc = [f.sceneId, f.beatId, f.lang].filter(Boolean).join(" ");
    log.fail(`${f.id} ${f.severity}${loc ? ` [${loc}]` : ""}: ${f.message} -> ${f.repair}`);
  }
  if (res.ok) {
    log.ok(`PREFLIGHT PASSED for ${res.bookId}/${res.chapterId}/${res.partId} (0 BLOCKER, 0 HIGH, ${res.summary.MEDIUM} MEDIUM)`);
    return 0;
  }
  log.warn(`PREFLIGHT FAILED for ${res.bookId}/${res.chapterId}/${res.partId} (BLOCKER ${res.summary.BLOCKER}, HIGH ${res.summary.HIGH})`);
  return 1;
}
